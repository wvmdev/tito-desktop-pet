// Dev tool: measure the visible (non-transparent) extent of every frame and write
// src/sprite-metrics.js. Run after changing sprites or sizes:  npx electron tools/metrics.js
//   half       furthest visible pixel from the image centre (rendered px at size 1) -> screen-edge margin
//   height     visible height above the image bottom (rendered px at size 1)
//   bottomPad  empty rows under the lowest visible pixel (SOURCE px), min..max over frames
const { app, nativeImage } = require('electron');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const SPRITES = path.join(ROOT, 'assets', 'sprites');
// Reuse the renderer's own size table so the numbers always match what is drawn.
const sandbox = { window: {}, console, requestAnimationFrame() {}, Image: function () {}, performance: { now: () => 0 } };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'src/renderer/animations.js'), 'utf8'), sandbox);
const { sizeFactor } = sandbox.window.TitoAnim;
const BASE_SCALE = 0.3; // keep in sync with renderer/pet.js

function frameBox(file) {
  const img = nativeImage.createFromPath(file);
  const { width: w, height: h } = img.getSize();
  const px = img.toBitmap(); // BGRA
  let l = w, r = -1, t = h, b = -1;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (px[(y * w + x) * 4 + 3] > 40) { if (x < l) l = x; if (x > r) r = x; if (y < t) t = y; if (y > b) b = y; }
  }
  return { w, h, l, r: r + 1, t, b: b + 1 };
}

app.whenReady().then(() => {
  const out = {};
  for (const a of fs.readdirSync(SPRITES).filter(d => !d.startsWith('.')).sort()) {
    const scale = BASE_SCALE * sizeFactor(a);
    let half = 0, height = 0, padMin = 1e9, padMax = 0;
    for (let i = 0; i < 8; i++) {
      const f = frameBox(path.join(SPRITES, a, `${a}_${i}.png`));
      half = Math.max(half, Math.max(f.w / 2 - f.l, f.r - f.w / 2) * scale);
      height = Math.max(height, (f.h - f.t) * scale);
      padMin = Math.min(padMin, f.h - f.b); padMax = Math.max(padMax, f.h - f.b);
    }
    out[a] = { half: Math.ceil(half), height: Math.ceil(height), padMin, padMax };
  }
  console.log('PAD', JSON.stringify(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, [v.padMin, v.padMax]]))));
  console.log('HALF', JSON.stringify(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.half]))));
  fs.writeFileSync(path.join(ROOT, 'src', 'sprite-metrics.js'),
    `// Generated by tools/metrics.js. Visible extent of every animation, in rendered px at size 1.\n` +
    `// half: furthest visible pixel from the image centre; height: visible height; pad: empty source rows under the paws.\n` +
    `module.exports = ${JSON.stringify(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, { half: v.half, height: v.height, pad: [v.padMin, v.padMax] }])), null, 1)};\n`);
  app.quit();
});
